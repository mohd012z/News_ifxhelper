'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const C=require('../bbma-lightweight-v5.js');
const base=Date.parse('2026-11-08T00:00:00Z');
const rows=Array.from({length:60},(_,i)=>({time:new Date(base+i*60000).toISOString(),open:100+i,high:102+i,low:99+i,close:101+i}));
const cutoff=new Date(base+60*60000).toISOString();
assert.equal(C.closed(rows,cutoff,1).length,60);
assert.equal(C.closed(rows,new Date(base+59*60000).toISOString(),1).length,59);
assert.throws(()=>C.closed([...rows,rows[0]],cutoff,1),/DUPLICATE_TIME/);
const ind=C.indicators(C.closed(rows,cutoff,1));
assert.equal(ind.ema50.filter(x=>x!==null).length,11);
assert.equal(ind.bbMiddle.filter(x=>x!==null).length,41);
assert.equal(ind.lwma5High.filter(x=>x!==null).length,56);
assert.equal(ind.lwma10Low.filter(x=>x!==null).length,51);
const input=[{pattern:'DBR',confirmedAt:rows[15].time,low:100,high:105},{pattern:'RBD',confirmedAt:rows[59].time,low:150,high:155},{pattern:'RBR',confirmedAt:new Date(base+61*60000).toISOString(),low:100,high:105}];
assert.equal(C.zones(input,C.closed(rows,cutoff,1),cutoff).length,2);
assert.equal(C.zones(input,C.closed(rows,cutoff,1),new Date(base+20*60000).toISOString()).length,1);
assert.equal(C.mount({},{}),null);
const dashboard=fs.readFileSync(require.resolve('../bbma-dashboard-ui.js'),'utf8');
assert(dashboard.includes('bbma-v5-toggle')&&dashboard.includes('window.__bbmaV5Instance.destroy()'));
const html=fs.readFileSync(require.resolve('../index.html'),'utf8');
assert(html.includes('bbma-lightweight-v5.js')&&html.includes('lightweight-charts@5.2.0'));
console.log('BBMA Lightweight Charts v5 deterministic adapter and SVG fallback tests passed');
