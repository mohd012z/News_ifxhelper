'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const listeners={};
const fixed=Date.UTC(2026,10,8,3,0,0);
class Clock extends Date { constructor(...args){super(...(args.length?args:[fixed]));} static now(){return fixed;} }
const ctx={Date:Clock,Math,Number,isFinite,CustomEvent:class{constructor(type,init){this.type=type;this.detail=init.detail;}},setInterval:()=>{},window:{addEventListener:(name,fn)=>{listeners[name]=fn;},dispatchEvent:()=>{}}};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync('bbma-runtime.js','utf8'),ctx);
const rt=ctx.window.BBMARuntime;
const first=rt.snapshot();
assert.equal(first.source,'SYNTHETIC_DEMO');
assert.equal(first.fresh,false);
assert.equal(first.frames.M15.state,'INSUFFICIENT_DATA');
assert.equal(first.alerts.length,0);
assert.equal(first.alertHistory.length,0);
assert.equal(rt.barBucket('MN1',Date.UTC(2026,1,28)),Date.UTC(2026,1,1));
assert.equal(rt.barBucket('MN1',Date.UTC(2026,2,1)),Date.UTC(2026,2,1));
assert.equal(rt.barEnd('MN1',Date.UTC(2024,1,1)),Date.UTC(2024,2,1));
assert.equal(rt.barEnd('MN1',Date.UTC(2026,11,1)),Date.UTC(2027,0,1));
const before=rt.frames.M5.length;
assert.equal(rt.ingest(2700,new Date(fixed).toISOString()),true);
assert.equal(rt.ingest(9999,new Date(fixed-300000).toISOString()),false);
assert.equal(rt.ingest(9999,new Date(fixed+120000).toISOString()),false);
assert.equal(rt.frames.M5.length,before);
assert.equal(rt.snapshot().frames.M5.state,'INSUFFICIENT_DATA');
assert.equal(rt.snapshot().alerts.length,0);
console.log('HELIX BBMA integrity regression passed');
