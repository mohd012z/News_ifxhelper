'use strict';
const assert=require('node:assert/strict');
const R=require('../lib/ohlc-resampler');
const B=require('../lib/ohlc-backfill');
const base=Date.parse('2026-09-23T00:00:00Z');
const candle=i=>({time:new Date(base+i*60000).toISOString(),open:100+i,high:101+i,low:99+i,close:100.5+i,volume:1});
const rows=Array.from({length:15},(_,i)=>candle(i));
const end=base+15*60000;
assert.equal(R.resample(rows,15,{asOf:end-1}).length,0,'forming M15 excluded');
assert.equal(R.resample(rows,15,{asOf:end}).length,1,'closed M15 accepted');
const duplicate=[...rows.slice(0,14),rows[13]];
assert.equal(R.resample(duplicate,15,{asOf:end}).length,0,'duplicate cannot replace missing minute');
const missing=rows.filter((_,i)=>i!==7);
assert.equal(R.resample(missing,15,{asOf:end}).length,0,'gap excluded');
const outOfOrder=[...rows].reverse();
assert.equal(R.resample(outOfOrder,15,{asOf:end})[0].close,114.5,'out-of-order sorted');
const future=[...rows,candle(15)];
assert.equal(R.resample(future,15,{asOf:end}).length,1,'future source cannot enter closed bucket');
const selected=B.select(rows,new Date(base+5*60000).toISOString(),{timeframeMinutes:1,now:end});
assert.equal(selected.candle.time,rows[4].time,'checkpoint matches candle CLOSE, not open');
assert.equal(selected.lagMinutes,0);
const later=B.select(rows,new Date(base+5.5*60000).toISOString(),{timeframeMinutes:1,now:end});
assert.equal(later.candle.time,rows[5].time,'next closed candle selected');
assert.equal(later.lagMinutes,0.5);
console.log('P0 temporal integrity regression passed');
