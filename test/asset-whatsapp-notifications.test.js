'use strict';
const assert=require('node:assert/strict');
const {classifyEvent,prioritizeEvents}=require('../lib/asset-news-relevance');
const {buildAssetNotifications}=require('../lib/asset-whatsapp-notifications');
const sample=(event,importance='high',currency='USD')=>({event,importance,currency,date:'2026-11-03',timeMyt:'20:30'});
assert(classifyEvent(sample('US CPI Inflation')).some(x=>x.asset==='XAUUSD'));
assert(classifyEvent(sample('US CPI Inflation')).some(x=>x.asset==='BTCUSD'));
assert(classifyEvent(sample('EIA crude oil inventories')).some(x=>x.asset==='OIL'));
assert.deepEqual(classifyEvent(sample('Bitcoin spot ETF inflows')).map(x=>x.asset),['BTCUSD']);
assert.deepEqual(classifyEvent(sample('Unrelated holiday','low','EUR')),[]);
assert.equal(prioritizeEvents([sample('Bitcoin spot ETF','low')],{impacts:['high']}).length,0);
assert.throws(()=>classifyEvent(sample('CPI'),{assets:['FAKE']}),/Unsupported/);
const out=buildAssetNotifications([sample('EIA crude oil inventories'),sample('Bitcoin spot ETF')]);
assert.equal(out.length,2);
assert(out[0].text.includes('Research only'));
assert(out.every(x=>x.requiresManualPublication));
assert(out.some(x=>x.assets.includes('OIL')));
assert(out.some(x=>x.assets.includes('BTCUSD')));
console.log('Asset-specific WhatsApp research tests passed');
