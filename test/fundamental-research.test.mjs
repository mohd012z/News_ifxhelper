import assert from 'node:assert/strict';
import {normalizeEvent,instruments,morningDue,stage,deliveryKey,numericSurprise,stance} from '../worker/fundamental-research.mjs';
const e=normalizeEvent({title:'CPI',country:'USD',impact:'Low',date:'2026-11-06T13:30:00Z',actual:'3',forecast:'2.8',previous:'2.7'});
assert(e);
assert.deepEqual(instruments(e,'news_ifxhelper'),['XAUUSD','BTCUSD']);
assert(instruments(e,'helix').includes('EURUSD'));
assert.equal(stance(e).bias,'Hawkish');
assert(Math.abs(numericSurprise(e).difference-0.2)<1e-9);
assert.equal(stage(e,e.time-30*60000),'T-30');
assert.equal(stage(e,e.time-10*60000),'T-10');
assert.equal(stage(e,e.time-2*60000),null);
assert.equal(stage(e,e.time+60000),'RESULT');
assert(morningDue(Date.parse('2026-11-06T00:00:00Z')));
assert(!morningDue(Date.parse('2026-11-06T00:01:00Z')));
assert.notEqual(deliveryKey('helix',e,'a','T-30'),deliveryKey('helix',e,'a','T-10'));
assert(!normalizeEvent({...e,date:'2026-11-06T13:30:00'}));
assert.deepEqual(instruments({...e,currency:'JPY'},'news_ifxhelper'),[]);
assert.equal(stance({...e,actual:null}).bias,'Unverified');
assert.equal(stance({...e,actual:'2.9%',forecast:'2.8%'}).bias,'Hawkish');
assert.equal(stance({...e,actual:'2.7%',forecast:'2.8%'}).bias,'Dovish');
assert.equal(stance({...e,title:'Unemployment Rate',actual:'4.3%',forecast:'4.1%'}).bias,'Dovish');
assert.equal(stance({...e,actual:'unavailable',forecast:'2.8%'}).bias,'Unverified');
console.log('PASS fundamental routing, MYT schedule, impact, result verification, stance, dedupe');
