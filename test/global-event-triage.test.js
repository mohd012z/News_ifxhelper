'use strict';
const assert=require('node:assert/strict');
const {classifyMacroTone,triageStory}=require('../lib/global-event-triage');
assert.equal(classifyMacroTone('Inflation remains elevated; further tightening').tone,'hawkish');
assert.equal(classifyMacroTone('Inflation has eased; policy easing').tone,'dovish');
assert.equal(classifyMacroTone('Rates held steady; inflation remains elevated but policy easing considered').tone,'inconclusive');
const quake=triageStory({provider:'usgs',verified:true,title:'Magnitude 6.8 earthquake',summary:'No confirmed energy infrastructure damage',importance:'high'});
assert.equal(quake.topic,'natural-disaster');
assert.equal(quake.marketEffect,'not-established');
assert.equal(quake.physicalImpactConfirmed,false);
const rumor=triageStory({provider:'twitter',verified:false,title:'Bitcoin ETF rumor',importance:'high'});
assert.equal(rumor.verification,'unverified');
assert.equal(rumor.publishableAsConfirmed,false);
assert(rumor.affectedAssets.includes('BTCUSD'));
const oil=triageStory({provider:'news',independentSources:2,verified:true,title:'Hormuz oil shipping disruption',infrastructureImpactConfirmed:true,marketReactionVerified:false,importance:'high'});
assert.equal(oil.topic,'geopolitical');
assert.equal(oil.marketEffect,'not-established');
assert(oil.affectedAssets.includes('OIL'));
console.log('Global-event triage tests passed');
