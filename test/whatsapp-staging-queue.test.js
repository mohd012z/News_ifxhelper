'use strict';
const assert=require('node:assert/strict');
const {makeJob,enqueueUnique,nextAttempt}=require('../lib/whatsapp-staging-queue');
const event={event:'CPI',date:'2026-11-03',timeMyt:'20:30',importance:'high'};
const opts={destination:'channel-draft',destinationId:'staging-channel',stage:'30'};
const first=enqueueUnique([], [event,event],opts);
assert.equal(first.added.length,1);
assert.equal(enqueueUnique(first.jobs,[event],opts).added.length,0);
assert.notEqual(makeJob(event,{...opts,destinationId:'other'}).key,first.jobs[0].key);
assert.equal(enqueueUnique([], [event],{...opts,impacts:['low']}).added.length,0);
assert.throws(()=>makeJob(event,{...opts,destination:'channel-live'}),/Unsupported/);
const now=Date.parse('2026-11-03T08:00:00Z');
const retry=nextAttempt(first.jobs[0],now);
assert.equal(retry.status,'retry');assert.equal(retry.attempts,1);
const retry2=nextAttempt(retry,now);
assert.equal(retry2.attempts,2);
const dead=nextAttempt(retry2,now);
assert.equal(dead.status,'dead-letter');assert.equal(dead.nextAttemptAt,null);
assert.equal(nextAttempt({...retry,status:'delivered'},now).status,'delivered');
console.log('WhatsApp staging queue tests passed');
