import assert from 'node:assert/strict';
import {weeklyDue,weeklyKey,weeklySummary,runWeeklyOutlook} from '../worker/helix-weekly-outlook.mjs';
const monday=Date.parse('2026-11-09T00:00:00Z');
assert.equal(weeklyDue(monday),true);
assert.equal(weeklyDue(monday+14*60000),true);
assert.equal(weeklyDue(monday+15*60000),false);
assert.equal(weeklyDue(monday-86400000),false);
assert.equal(weeklyKey(monday,'@ifxhelper2'),weeklyKey(monday+300000,'@ifxhelper2'));
const feed=[{title:'US CPI <release>',country:'USD',impact:'High',date:new Date(monday+86400000).toISOString(),forecast:'3%',previous:'2.8%'},{title:'Old',country:'USD',impact:'High',date:new Date(monday-1000).toISOString()}];
const summary=weeklySummary(feed,monday);
assert.equal(summary.count,1);assert.match(summary.text,/&lt;release&gt;/);assert.ok(summary.text.length<4096);
let claimed=false,telegram=0;
const db={prepare(sql){return {bind(){return {async run(){if(sql.includes('INSERT OR IGNORE')){if(claimed)return {meta:{changes:0}};claimed=true;}return {meta:{changes:1}};}}}}}};
const fetchImpl=async(url,options)=>url.includes('ff_calendar')?{ok:true,json:async()=>feed}:(telegram++,assert.equal(JSON.parse(options.body).chat_id,'@ifxhelper2'),{ok:true,json:async()=>({ok:true,result:{message_id:44}})});
const env={ENABLE_HELIX_WEEKLY_OUTLOOK:'true',ENABLE_HELIX_CHANNEL_DELIVERY:'true',HELIX_CHANNEL_ONLY:'true',TELEGRAM_CHANNEL_ID:'@ifxhelper2',REMINDER_DB:db,TELEGRAM_BOT_TOKEN:'mock'};
assert.equal((await runWeeklyOutlook(env,{now:monday,fetchImpl})).sent,true);
assert.equal((await runWeeklyOutlook(env,{now:monday+300000,fetchImpl})).skipped,true);
assert.equal(telegram,1);
await assert.rejects(()=>runWeeklyOutlook({...env,ENABLE_HELIX_CHANNEL_DELIVERY:'false'},{now:monday,fetchImpl}),/not authorized/);
assert.equal((await runWeeklyOutlook({...env,ENABLE_HELIX_WEEKLY_OUTLOOK:'false'},{now:monday,fetchImpl})).disabled,true);
console.log('HELIX Monday weekly outlook timing, channel, dedupe and security tests passed');
