'use strict';
/**
 * Key-free MT-F ATR collector for Yahoo GC=F gold FUTURES only.
 * Instruments can be changed by injecting broker OHLC into analyzeAll(); this
 * collector never impersonates an XAU/USD spot feed.
 */
const fs=require('node:fs'),path=require('node:path');
const Provider=require('./lib/market-provider');
const Engine=require('./lib/atr-mtf-engine');
const OUT=path.join(__dirname,'atr-mtf.js');
const FEEDS=[
  {key:'1m',interval:'1m',range:'5d'},
  {key:'5m',interval:'5m',range:'1mo'},
  {key:'1h',interval:'1h',range:'3mo'},
  {key:'1d',interval:'1d',range:'5y'}
];
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
async function collect({fetcher=Provider.yahoo,now=Date.now(),symbol='GC=F'}={}){
  // The Yahoo source must remain declared as futures. Other symbols require
  // a reviewed provider-identity mapping before they can be enabled here.
  if(symbol!=='GC=F')throw Error('UNSUPPORTED_COLLECTOR_SYMBOL');
  const sets={},feeds={};
  for(const f of FEEDS){
    try{
      const resp=await fetcher(symbol,{interval:f.interval,range:f.range,timeoutMs:12000});
      if(!resp||!Array.isArray(resp.candles))throw Error('MISSING_OHLC');
      sets[f.key]=resp.candles;
      feeds[f.key]={state:'OK',count:resp.candles.length,provider:resp.provider};
    }catch(e){
      sets[f.key]=[];
      feeds[f.key]={state:'ERROR',reason:String(e.message||e).slice(0,160)};
    }
    await sleep(150);
  }
  const out=Engine.analyzeAll(sets,{now,instrument:'GC=F',provider:'YAHOO_CHART',source:'yahoo:GC=F'});
  return {...out,feeds,market:'GOLD_FUTURES_PROXY',displaySymbol:'GC=F',notSpot:true};
}
function persist(out,file=OUT){
  // Atomic rewrite avoids accidentally exposing half-written market data.
  const code='/* Generated by build-atr-mtf.js; Yahoo GC=F futures proxy, not XAU/USD spot. */\n'
    +'window.ATR_MTF = '+JSON.stringify(out,null,2)+';\n';
  const temp=file+'.tmp';
  fs.writeFileSync(temp,code,'utf8');fs.renameSync(temp,file);
  return file;
}
async function main(){
  const out=await collect();
  persist(out);
  console.log('MTF ATR14',out.state,out.readyCount+'/'+out.total,
    Object.values(out.timeframes).map(x=>x.tf+':'+x.state+(x.reason?'/'+x.reason:'')).join(' '));
  if(out.readyCount===0)console.warn('WARN MTF: no recent usable ATR bars; no TP must be generated');
}
if(require.main===module)main().catch(e=>{console.error('MTF build failed:',e.message);process.exitCode=1});
module.exports={FEEDS,collect,persist};
